import AppKit
import UniformTypeIdentifiers
import Vision

/// Watches the general pasteboard and keeps the newest-first history, persisted under
/// ~/Library/Application Support/ClipboardHistory (index.json + items/<id>.plist and <id>.png thumbnails).
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    /// Copies apps mark as private (password managers etc.); see nspasteboard.org.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    private static let maxItemBytes = 100 * 1024 * 1024

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = -1 // capture whatever is on the clipboard at launch
    private var timer: Timer?
    private let ioQueue = DispatchQueue(label: "clipboard-history.io")
    private let indexURL: URL
    private let itemsDirectory: URL

    var maxItems: Int {
        let value = UserDefaults.standard.integer(forKey: "maxItems")
        return value > 0 ? value : 200
    }

    init() {
        let directory = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipboardHistory", isDirectory: true)
        indexURL = directory.appendingPathComponent("index.json")
        itemsDirectory = directory.appendingPathComponent("items", isDirectory: true)
        try? FileManager.default.createDirectory(at: itemsDirectory, withIntermediateDirectories: true)

        if let data = try? Data(contentsOf: indexURL),
           let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            items = saved
        }
        // Text kept by an older reading of images is read again.
        if UserDefaults.standard.integer(forKey: Self.imageTextReadingKey) != Self.imageTextReading {
            deleteImageTexts(of: items)
            for index in items.indices { items[index].hasImageText = nil }
            UserDefaults.standard.set(Self.imageTextReading, forKey: Self.imageTextReadingKey)
            saveIndex()
        }
        removeOrphanedFiles()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.1
    }

    // MARK: Capture

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let reps = ClipboardItem.capture(pasteboard)
        let byteCount: Int = reps.joined().reduce(0) { $0 + $1.data.count }
        guard byteCount <= Self.maxItemBytes,
              let item = ClipboardItem(representations: reps, sourceBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
        else { return }

        if let index = items.firstIndex(where: { $0.contentHash == item.contentHash }) {
            var existing = items.remove(at: index)
            existing.date = item.date
            items.insert(existing, at: 0)
        } else {
            // The thumbnail is on disk before the row first draws; the list caches a missing one for good.
            if let thumbnail = Self.makeThumbnail(for: item, reps: reps) {
                try? thumbnail.write(to: thumbnailURL(for: item), options: .atomic)
            }
            items.insert(item, at: 0)
            let dataURL = dataURL(for: item)
            ioQueue.async {
                try? Self.encode(reps).write(to: dataURL, options: .atomic)
            }
        }
        trimToMaxItems()
        saveIndex()
    }

    // MARK: Actions

    /// Puts the item back on the clipboard with all its original types (or, with `plainText`, its plain text
    /// alone), and with `moveToTop` makes it the newest entry.
    @discardableResult
    func copyToPasteboard(_ item: ClipboardItem, moveToTop: Bool, plainText: Bool = false) -> Bool {
        guard let reps = representations(of: item) else { return false }

        if plainText {
            guard let data = reps.lazy.flatMap({ $0 }).first(where: { $0.type == UTType.utf8PlainText.identifier })?.data,
                  let text = String(data: data, encoding: .utf8) else { return false }
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
        } else {
            pasteboard.clearContents()
            pasteboard.writeObjects(reps.map { rep in
                let pasteboardItem = NSPasteboardItem()
                for (type, data) in rep {
                    pasteboardItem.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
                return pasteboardItem
            })
        }
        lastChangeCount = pasteboard.changeCount

        if moveToTop, let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            saveIndex()
        }
        return true
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: [item])
        saveIndex()
    }

    func clear() {
        deleteFiles(of: items)
        items.removeAll()
        saveIndex()
    }

    // MARK: Images

    /// The item's image at most `maxPixelSize` on its longer side, for the preview; slow for big images, so call it off the main thread.
    func previewImage(for item: ClipboardItem, maxPixelSize: Int) -> CGImage? {
        guard item.isImage else { return nil }
        let reps = item.imageFilePath == nil ? representations(of: item) ?? [] : []
        return Self.scaledImage(for: item, reps: reps, maxPixelSize: maxPixelSize)
    }

    /// The text read from the item's image, or nil if there is none. Slow for big images, so call it off the main thread.
    func recognizeText(in item: ClipboardItem) -> String? {
        guard item.isImage else { return nil }
        let reps = item.imageFilePath == nil ? representations(of: item) ?? [] : []
        return Self.scaledImage(for: item, reps: reps, maxPixelSize: 4096).flatMap(Self.recognizedText)
    }

    /// Vision's on-device text recognition, laid out as the text sat in the image (see `layOut`).
    static func recognizedText(in image: CGImage) -> String? {
        let request = textRequest()
        guard (try? VNImageRequestHandler(cgImage: image).perform([request])) != nil else { return nil }
        let lines = (request.results ?? []).enumerated().compactMap { RecognizedLine($1, id: $0) }
        return layOut(withNumberColumnRecovered(lines, in: image))
    }

    private static func textRequest() -> VNRecognizeTextRequest {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        request.automaticallyDetectsLanguage = true
        return request
    }

    /// Bumped when the text button reads images better, so text kept from an older reading is read again.
    private static let imageTextReading = 2
    private static let imageTextReadingKey = "imageTextReading"

    /// Vision misses small, dim numbers standing alone in a column, such as the line numbers beside code: it finds
    /// some and not others, and not the same ones at another size. When it has found at least two numbers in a
    /// column, the column is read again on its own at several sizes, and each row takes the reading most of the
    /// passes agree on. Only numbers are taken from the passes; nothing is added where no pass read a number.
    private static func withNumberColumnRecovered(_ lines: [RecognizedLine], in image: CGImage) -> [RecognizedLine] {
        func isNumber(_ line: RecognizedLine) -> Bool {
            line.words.count == 1 && line.words[0].text.count <= 4 && line.words[0].text.allSatisfy(\.isNumber)
        }
        let numbers = lines.filter(isNumber)
        guard numbers.count >= 2 else { return lines }
        let digitWidth = max(numbers.map { $0.box.width }.sorted()[numbers.count / 2], 0.002)
        // The numbers that share a left or a right edge (line numbers are often right-aligned).
        func largestGroup(sharing edge: KeyPath<CGRect, CGFloat>) -> [RecognizedLine] {
            var best: [RecognizedLine] = []
            for anchor in numbers {
                let group = numbers.filter { abs($0.box[keyPath: edge] - anchor.box[keyPath: edge]) < 1.5 * digitWidth }
                if group.count > best.count { best = group }
            }
            return best
        }
        let leftAligned = largestGroup(sharing: \.minX), rightAligned = largestGroup(sharing: \.maxX)
        let alignsRight = rightAligned.count > leftAligned.count
        let column = alignsRight ? rightAligned : leftAligned
        guard column.count >= 2 else { return lines }

        let columnLeft = column.map { $0.box.minX }.min()!, columnRight = column.map { $0.box.maxX }.max()!
        let left = max(0, columnLeft - 2 * digitWidth), right = min(1, columnRight + 2 * digitWidth)

        // Each pass: the numbers it read, in the image's own space. The strip is as tall as the image, so rows keep
        // their place. Which numbers Vision sees changes with the width of the strip too, so that varies as well.
        var readings: [(text: String, box: CGRect)] = column.map { ($0.words[0].text, $0.box) }
        for padding in [0.5, 1, 2] as [CGFloat] {
            let stripX = Int((max(0, columnLeft - padding * digitWidth) * CGFloat(image.width)).rounded(.down))
            let stripWidth = Int((min(1, columnRight + padding * digitWidth) * CGFloat(image.width)).rounded(.up)) - stripX
            guard stripWidth >= 4, let strip = image.cropping(to: CGRect(x: stripX, y: 0, width: stripWidth, height: image.height)) else { continue }
            let stripLeft = CGFloat(stripX) / CGFloat(image.width)
            let stripSpan = CGFloat(stripWidth) / CGFloat(image.width)
            for factor in [2, 3, 4, 5, 6] as [CGFloat] {
                let width = Int(CGFloat(stripWidth) * factor), height = Int(CGFloat(image.height) * factor)
                guard height <= 12_000,
                      let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                              space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
                else { continue }
                context.interpolationQuality = .high
                context.draw(strip, in: CGRect(x: 0, y: 0, width: width, height: height))
                let request = textRequest()
                guard let enlarged = context.makeImage(),
                      (try? VNImageRequestHandler(cgImage: enlarged).perform([request])) != nil else { continue }
                for observation in request.results ?? [] {
                    guard let text = observation.topCandidates(1).first?.string, text.count <= 4, text.allSatisfy(\.isNumber) else { continue }
                    let box = observation.boundingBox
                    readings.append((text, CGRect(x: stripLeft + box.minX * stripSpan, y: box.minY, width: box.width * stripSpan, height: box.height)))
                }
            }
        }

        // One line per row of the column, reading what most passes read there.
        var rows: [[(text: String, box: CGRect)]] = []
        for reading in readings.sorted(by: { $0.box.maxY > $1.box.maxY }) {
            if let index = rows.firstIndex(where: { row in
                row.contains { min($0.box.maxY, reading.box.maxY) - max($0.box.minY, reading.box.minY) > 0.5 * reading.box.height }
            }) {
                rows[index].append(reading)
            } else {
                rows.append([reading])
            }
        }
        let recovered: [RecognizedLine] = rows.enumerated().map { index, row in
            let votes = Dictionary(grouping: row, by: \.text)
            let best = votes.max { $0.value.count < $1.value.count }!.value
            let box = best.map(\.box).reduce(best[0].box) { $0.union($1) }
            let word = RecognizedWord(text: best[0].text, minX: box.minX, maxX: box.maxX, line: -1 - index)
            return RecognizedLine(words: [word], box: box, characterCount: best[0].text.count)
        }
        // They replace the numbers the first pass read in that column.
        let kept = lines.filter { !(isNumber($0) && $0.box.minX >= left - 0.0001 && $0.box.maxX <= right + 0.0001) }
        let inferred = completingCount(recovered, alignsRight: alignsRight, beside: kept)
        NSLog("Number column: %d read, %d inferred", recovered.count, inferred.count)
        return kept + recovered + inferred
    }

    /// Line numbers are a count. Where the numbers that were read run down the image in one steady count, the ones
    /// between them that no pass read are put back, and so are the ones above and below that sit beside recognised
    /// text. Those are inferred, not read, so nothing is added unless the count is steady: a wrapped line, a second
    /// column of numbers or a stray number breaks it, and then the numbers stay as they were read.
    private static func completingCount(_ numbers: [RecognizedLine], alignsRight: Bool, beside text: [RecognizedLine]) -> [RecognizedLine] {
        let top = numbers.sorted { $0.box.midY > $1.box.midY }
        let values = top.compactMap { Int($0.words[0].text) }
        guard top.count >= 3, values.count == top.count,
              zip(values, values.dropFirst()).allSatisfy({ $0 < $1 }) else { return [] }
        // The spacing of one number step, and where the count's line falls at the first number's value.
        let steps = (0..<top.count - 1).map { (top[$0].box.midY - top[$0 + 1].box.midY) / CGFloat(values[$0 + 1] - values[$0]) }
        let pitch = steps.sorted()[steps.count / 2]
        guard pitch > 0 else { return [] }
        let offsets = (0..<top.count).map { top[$0].box.midY + CGFloat(values[$0] - values[0]) * pitch }
        let firstY = offsets.sorted()[offsets.count / 2]
        func y(of value: Int) -> CGFloat { firstY - CGFloat(value - values[0]) * pitch }
        guard zip(top, values).allSatisfy({ abs($0.box.midY - y(of: $1)) <= 0.25 * pitch }) else { return [] }

        func line(for value: Int) -> RecognizedLine {
            let nearest = zip(top, values).min { abs($0.1 - value) < abs($1.1 - value) }!.0
            let digits = String(value).count
            let width = nearest.box.width * CGFloat(digits) / CGFloat(nearest.words[0].text.count)
            let x = alignsRight ? nearest.box.maxX - width : nearest.box.minX
            let box = CGRect(x: x, y: y(of: value) - nearest.box.height / 2, width: width, height: nearest.box.height)
            let word = RecognizedWord(text: String(value), minX: box.minX, maxX: box.maxX, line: -1000 - value)
            return RecognizedLine(words: [word], box: box, characterCount: digits)
        }
        func besideText(_ value: Int) -> Bool {
            let centre = y(of: value)
            return text.contains { centre >= $0.box.minY && centre <= $0.box.maxY }
        }
        let read = Set(values)
        var added = (values[0]...values[values.count - 1]).filter { !read.contains($0) }.map(line)
        var above = values[0] - 1
        while above >= 1, besideText(above) {
            added.append(line(for: above))
            above -= 1
        }
        var below = values[values.count - 1] + 1
        while besideText(below) {
            added.append(line(for: below))
            below += 1
        }
        return added
    }

    /// A word, and where Vision found it. Positions are in the image's own space: 0 to 1 across and up.
    private struct RecognizedWord {
        let text: String
        let minX: CGFloat
        let maxX: CGFloat
        /// Which recognised line it came from; words of one line were separated by a space.
        let line: Int
    }

    /// One line of recognised text.
    private struct RecognizedLine {
        let words: [RecognizedWord]
        let box: CGRect
        let characterCount: Int

        init(words: [RecognizedWord], box: CGRect, characterCount: Int) {
            self.words = words
            self.box = box
            self.characterCount = characterCount
        }

        init?(_ observation: VNRecognizedTextObservation, id: Int) {
            guard let candidate = observation.topCandidates(1).first else { return nil }
            let string = candidate.string
            var words: [RecognizedWord] = []
            var index = string.startIndex
            while let start = string[index...].firstIndex(where: { !$0.isWhitespace }) {
                let end = string[start...].firstIndex(where: \.isWhitespace) ?? string.endIndex
                guard let box = (try? candidate.boundingBox(for: start..<end))?.boundingBox else { break }
                words.append(RecognizedWord(text: String(string[start..<end]), minX: box.minX, maxX: box.maxX, line: id))
                index = end
            }
            // A word whose box Vision wouldn't give: keep the line whole, placed by its own box.
            if words.isEmpty || words.map({ $0.text.count }).reduce(0, +) != string.filter({ !$0.isWhitespace }).count {
                let text = string.trimmingCharacters(in: .whitespaces)
                guard !text.isEmpty else { return nil }
                words = [RecognizedWord(text: text, minX: observation.boundingBox.minX, maxX: observation.boundingBox.maxX, line: id)]
            }
            self.words = words
            box = observation.boundingBox
            characterCount = string.count
        }
    }

    /// The width of one character, if the words are set in a monospaced font; nil otherwise. A word's width is its
    /// letter count times the character width, plus a fixed padding, so a straight line through (letters, width)
    /// gives the character width, and how closely the words sit on it tells monospaced text from proportional.
    private static func monospacedAdvance(of words: [RecognizedWord]) -> CGFloat? {
        let words = words.filter { $0.text.count >= 3 }
        guard words.count >= 4 else { return nil }
        let counts = words.map { CGFloat($0.text.count) }
        let widths = words.map { $0.maxX - $0.minX }
        let meanCount = counts.reduce(0, +) / CGFloat(words.count)
        let meanWidth = widths.reduce(0, +) / CGFloat(words.count)
        let spread = counts.map { ($0 - meanCount) * ($0 - meanCount) }.reduce(0, +)
        guard spread > 0 else { return nil }
        let slope = zip(counts, widths).map { ($0 - meanCount) * ($1 - meanWidth) }.reduce(0, +) / spread
        guard slope > 0 else { return nil }
        let intercept = meanWidth - slope * meanCount
        let misfit = zip(counts, widths).map { abs($1 - (slope * $0 + intercept)) / $1 }.sorted()[words.count / 2]
        return misfit < monospacedMisfit ? slope : nil
    }
    private static let monospacedMisfit: CGFloat = 0.06

    /// Puts the lines back where they sat, as plain text: the indent, the gaps between columns and the blank
    /// lines between paragraphs, which Vision doesn't report, are worked out from where each word is. A character is
    /// as wide as the typical recognised line is per character, so it's exact for monospaced text (code,
    /// terminals, tables) and close for the rest, where an ordinary space between words stays a single space.
    private static func layOut(_ lines: [RecognizedLine]) -> String? {
        guard !lines.isEmpty else { return nil }
        func median(_ values: [CGFloat]) -> CGFloat {
            values.sorted()[values.count / 2]
        }
        let measured = lines.filter { $0.characterCount >= 3 }
        let characterWidth = max(median((measured.isEmpty ? lines : measured).map { $0.box.width / CGFloat($0.characterCount) }), 0.0001)
        let lineHeight = max(median(lines.map(\.box.height)), 0.0001)

        // Lines that share a row of the image (the cells of a table, say) are one row, read left to right.
        struct Row {
            var lines: [RecognizedLine]
            var minY: CGFloat
            var maxY: CGFloat
            var words: [RecognizedWord] { lines.flatMap(\.words).sorted { $0.minX < $1.minX } }
        }
        var rows: [Row] = []
        for line in lines.sorted(by: { $0.box.midY > $1.box.midY }) {
            if let last = rows.last, let first = last.lines.first,
               min(last.maxY, line.box.maxY) - max(last.minY, line.box.minY) > 0.5 * min(first.box.height, line.box.height) {
                rows[rows.count - 1].lines.append(line)
                rows[rows.count - 1].minY = min(last.minY, line.box.minY)
                rows[rows.count - 1].maxY = max(last.maxY, line.box.maxY)
            } else {
                rows.append(Row(lines: [line], minY: line.box.minY, maxY: line.box.maxY))
            }
        }

        func spaces(forGap gap: CGFloat) -> Int {
            let width = gap / characterWidth
            return width < 1.5 ? 1 : min(24, Int(width.rounded()))
        }
        let margin = rows.flatMap(\.words).map(\.minX).min() ?? 0
        let advance = monospacedAdvance(of: lines.flatMap(\.words))
        var output: [String] = []
        for (index, row) in rows.enumerated() {
            if index > 0 {
                let blank = Int(((rows[index - 1].minY - row.maxY) / lineHeight).rounded(.down))
                output += Array(repeating: "", count: min(max(blank, 0), 3))
            }
            var text = ""
            var previous: RecognizedWord?
            for word in row.words {
                if let previous {
                    if let advance {
                        // Where the word starts, not where the last one ended: a word's box is a little wider than
                        // its letters, which would shave a space off every gap. Words that start where the last one
                        // ended touch, whatever Vision's text says: its language correction puts a space in "foo (bar)".
                        let column = Int(((word.minX - margin) / advance).rounded())
                        text += String(repeating: " ", count: max(column - text.count, 0))
                    } else {
                        text += String(repeating: " ", count: spaces(forGap: word.minX - previous.maxX))
                    }
                } else {
                    text += String(repeating: " ", count: max(0, Int(((word.minX - margin) / (advance ?? characterWidth)).rounded())))
                }
                text += word.text
                previous = word
            }
            output.append(text)
        }
        return output.joined(separator: "\n")
    }

    /// Puts plain text on the clipboard without recording it as a new copy.
    func copyTextToPasteboard(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: Text in images

    /// The text already read from the item's image, so pasting it again waits for nothing.
    func cachedImageText(for item: ClipboardItem) -> String? {
        guard item.hasImageText == true else { return nil }
        let url = imageTextURL(for: item.id)
        return ioQueue.sync { try? String(contentsOf: url, encoding: .utf8) }
    }

    /// Remembers what the text button read from an image (nil: there was none), across restarts.
    func setImageText(_ text: String?, for id: UUID) {
        // The entry may have been deleted while it was being read.
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].hasImageText = text != nil
        if let text {
            let url = imageTextURL(for: id)
            ioQueue.async { try? text.write(to: url, atomically: true, encoding: .utf8) }
        }
        saveIndex()
    }

    private var warmedUpTextRecognition = false

    /// The first read in a process loads the recognition model, which can take many seconds; reading a small text
    /// ahead of the first click, once, when there's an image to read, gets that over with.
    func warmUpTextRecognition() {
        guard !warmedUpTextRecognition, items.contains(where: \.isImage) else { return }
        warmedUpTextRecognition = true
        DispatchQueue.global(qos: .utility).async {
            let started = Date()
            let width = 240, height = 64
            guard let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                          space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
            else { return }
            context.setFillColor(CGColor(gray: 1, alpha: 1))
            context.fill(CGRect(x: 0, y: 0, width: width, height: height))
            context.textPosition = CGPoint(x: 12, y: 20)
            let line = CTLineCreateWithAttributedString(NSAttributedString(
                string: "Clipboard text", attributes: [.font: NSFont.systemFont(ofSize: 28), .foregroundColor: NSColor.black]))
            CTLineDraw(line, context)
            _ = context.makeImage().flatMap(Self.recognizedText)
            NSLog("Text recognition warmed up in %.1f s", Date().timeIntervalSince(started))
        }
    }

    private func deleteImageTexts(of removed: [ClipboardItem]) {
        let urls = removed.map { imageTextURL(for: $0.id) }
        ioQueue.async { urls.forEach { try? FileManager.default.removeItem(at: $0) } }
    }

    private func imageTextURL(for id: UUID) -> URL {
        itemsDirectory.appendingPathComponent("\(id.uuidString).txt")
    }

    /// A file holding the item's image that another app can open: the copied file itself, or the copied data
    /// written to a temporary file named for its type.
    func imageFileURL(for item: ClipboardItem) -> URL? {
        if let path = item.imageFilePath { return URL(fileURLWithPath: path) }
        guard item.category == .image, let reps = representations(of: item), let image = Self.imageData(in: reps) else { return nil }
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("ClipboardHistory", isDirectory: true)
        let fileExtension = UTType(image.type)?.preferredFilenameExtension ?? "png"
        let url = directory.appendingPathComponent("\(item.title) \(item.id.uuidString.prefix(8)).\(fileExtension)")
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try image.data.write(to: url, options: .atomic)
        } catch {
            return nil
        }
        return url
    }

    // MARK: Storage

    private func representations(of item: ClipboardItem) -> [PasteboardRepresentation]? {
        let url = dataURL(for: item)
        return ioQueue.sync { try? Data(contentsOf: url) }.flatMap(Self.decode)
    }

    func thumbnailURL(for item: ClipboardItem) -> URL {
        itemsDirectory.appendingPathComponent("\(item.id.uuidString).png")
    }

    private func dataURL(for item: ClipboardItem) -> URL {
        itemsDirectory.appendingPathComponent("\(item.id.uuidString).plist")
    }

    private func trimToMaxItems() {
        guard items.count > maxItems else { return }
        deleteFiles(of: Array(items[maxItems...]))
        items.removeSubrange(maxItems...)
    }

    private func saveIndex() {
        let snapshot = items, url = indexURL
        ioQueue.async {
            try? JSONEncoder().encode(snapshot).write(to: url, options: .atomic)
        }
    }

    private func deleteFiles(of removed: [ClipboardItem]) {
        let urls = removed.flatMap { [dataURL(for: $0), thumbnailURL(for: $0), imageTextURL(for: $0.id)] }
        ioQueue.async {
            urls.forEach { try? FileManager.default.removeItem(at: $0) }
        }
    }

    private func removeOrphanedFiles() {
        let known = Set(items.map(\.id.uuidString))
        let directory = itemsDirectory
        ioQueue.async {
            let files = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
            for file in files where !known.contains(file.deletingPathExtension().lastPathComponent) {
                try? FileManager.default.removeItem(at: file)
            }
        }
    }

    private static func encode(_ reps: [PasteboardRepresentation]) -> Data {
        let plist = reps.map { rep in rep.map { ["type": $0.type, "data": $0.data] as [String: Any] } }
        return (try? PropertyListSerialization.data(fromPropertyList: plist, format: .binary, options: 0)) ?? Data()
    }

    private static func decode(_ data: Data) -> [PasteboardRepresentation]? {
        guard let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [[[String: Any]]] else { return nil }
        return plist.map { rep in
            rep.compactMap { entry in
                guard let type = entry["type"] as? String, let data = entry["data"] as? Data else { return nil }
                return (type, data)
            }
        }
    }

    /// A small PNG for image copies and copied image files, so the list never loads full-size data.
    private static func makeThumbnail(for item: ClipboardItem, reps: [PasteboardRepresentation]) -> Data? {
        scaledImage(for: item, reps: reps, maxPixelSize: 128)
            .flatMap { NSBitmapImageRep(cgImage: $0).representation(using: .png, properties: [:]) }
    }

    private static func scaledImage(for item: ClipboardItem, reps: [PasteboardRepresentation], maxPixelSize: Int) -> CGImage? {
        var source: CGImageSource?
        if let path = item.imageFilePath {
            source = CGImageSourceCreateWithURL(URL(fileURLWithPath: path) as CFURL, nil)
        } else if item.category == .image, let image = imageData(in: reps) {
            source = CGImageSourceCreateWithData(image.data as CFData, nil)
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        return source.flatMap { CGImageSourceCreateThumbnailAtIndex($0, 0, options as CFDictionary) }
    }

    private static func imageData(in reps: [PasteboardRepresentation]) -> (type: String, data: Data)? {
        reps.lazy.flatMap { $0 }.first { UTType($0.type)?.conforms(to: .image) == true }
    }
}
